# Merged talks where the speaker is an author of the other merged paper only;
# the importer records them as non-author presenters (metadata.presenter_name).
NON_AUTHOR_PRESENTERS = {
    ("Learning quantum states prepared by shallow circuits in polynomial time", "Isaac Kim"),
}


def add_note(notes: str, note: str) -> str:
    parts = [p.strip() for p in notes.split(";") if p.strip()]
    parts = [p for p in parts if not p.startswith("presenter=")]
    parts.append(note)
    return "; ".join(parts)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", action="store_true", help="update the CSV files")
    args = ap.parse_args()
    by_file = defaultdict(list)
    for entry in PRESENTERS:
        by_file[entry[0]].append(entry)
    changed = already = 0
    for rel, entries in sorted(by_file.items()):
        path = ROOT / "data/conferences" / rel
        raw = path.read_bytes()
        eol = "\r\n" if b"\r\n" in raw else "\n"
        rows = list(csv.DictReader(io.StringIO(raw.decode("utf-8"), newline="")))
        for _, title, presenters, kind, _evidence in entries:
            hits = [r for r in rows if r["title"] == title]
            assert len(hits) == 1, (rel, title, len(hits))
            r = hits[0]
            authors = [a.strip() for a in r["authors"].split(";") if a.strip()]
            new = ";".join(presenters)
            if r["speakers"] == new:
                already += 1
                continue
            assert not r["speakers"].strip(), (rel, title, r["speakers"])
            for p in presenters:
                assert p in authors or (title, p) in NON_AUTHOR_PRESENTERS, (rel, title, p)
            r["speakers"] = new
            r["notes"] = add_note(r.get("notes") or "", f"presenter={kind}")
            changed += 1
        if args.write:
            buf = io.StringIO()
            w = csv.DictWriter(buf, fieldnames=list(rows[0].keys()), lineterminator=eol)
            w.writeheader()
            w.writerows(rows)
            path.write_bytes(buf.getvalue().encode("utf-8"))
    print(f"{changed} presenters set, {already} already set"
          + ("" if args.write else " (report only; pass --write)"))


if __name__ == "__main__":
    main()
